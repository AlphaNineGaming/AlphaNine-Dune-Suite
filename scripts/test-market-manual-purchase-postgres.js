"use strict";
// Opt-in integration checks. All writes target session-local pg_temp tables;
// no live game relation is read or modified by these tests.
const assert = require("assert/strict");
const fs = require("fs");
const { Client } = require("pg");
const purchase = require("../lib/market-manual-purchase");
const configFile = process.env.ALPHANINE_TEST_PG_CONFIG;
if (!configFile) throw new Error("Set ALPHANINE_TEST_PG_CONFIG to a Suite connection config to run isolated temporary-table tests.");
const cfg = JSON.parse(fs.readFileSync(configFile,"utf8"));
const client = new Client({host:cfg.databaseHost,port:cfg.databasePort,database:cfg.databaseName,user:cfg.databaseUser,password:cfg.databasePassword,connectionTimeoutMillis:10000,application_name:"AlphaNine manual purchase TEMP TABLE tests"});
function isolated(sql) {
  const result = sql.replace(/\bdune\./g,"pg_temp.");
  assert(!/\bdune\./.test(result));
  return result;
}
async function reset() {
  await client.query("TRUNCATE pg_temp.dune_exchange_fulfilled_orders,pg_temp.dune_exchange_sell_orders,pg_temp.dune_exchange_orders,pg_temp.items CASCADE");
  await client.query(`INSERT INTO pg_temp.items VALUES(30,'Item_Test',20,3);
    INSERT INTO pg_temp.dune_exchange_orders(id,exchange_id,access_point_id,owner_id,template_id,item_id,item_price,expiration_time,is_npc_order) VALUES(100,10,11,4,'Item_Test',30,100000,9429712,false);
    INSERT INTO pg_temp.dune_exchange_sell_orders VALUES(100);`);
}
async function inspect() {
  const result=await client.query(isolated(purchase.buildInspectSql("100")));
  return result.rows.length ? JSON.parse(Object.values(result.rows[0])[0]) : null;
}
async function apply(expected) {
  try { return await client.query(isolated(purchase.buildApplySql(expected))); }
  catch(error) { await client.query("ROLLBACK"); throw error; }
}
async function assertIntact() {
  const result=await client.query(`SELECT (SELECT count(*) FROM pg_temp.dune_exchange_orders)::int orders,
    (SELECT count(*) FROM pg_temp.dune_exchange_sell_orders)::int sells,
    (SELECT count(*) FROM pg_temp.items)::int items,
    (SELECT count(*) FROM pg_temp.dune_exchange_fulfilled_orders)::int claims`);
  assert.deepEqual(result.rows[0],{orders:1,sells:1,items:1,claims:0});
}
async function main() {
  await client.connect();
  try {
    await client.query(`CREATE TEMP TABLE accounts(id bigint PRIMARY KEY);
      CREATE TEMP TABLE actors(id bigint PRIMARY KEY,owner_account_id bigint REFERENCES pg_temp.accounts(id));
      CREATE TEMP TABLE inventories(id bigint PRIMARY KEY,exchange_id bigint);
      CREATE TEMP TABLE dune_exchanges(id bigint PRIMARY KEY,inventory_id bigint REFERENCES pg_temp.inventories(id));
      CREATE TEMP TABLE dune_exchange_accesspoints(id bigint PRIMARY KEY,exchange_id bigint REFERENCES pg_temp.dune_exchanges(id));
      CREATE TEMP TABLE dune_exchange_users(id bigint PRIMARY KEY,owner_id bigint REFERENCES pg_temp.actors(id));
      CREATE TEMP TABLE farm_variables(universe_time_timestamp timestamp,one_row boolean PRIMARY KEY);
      CREATE TEMP TABLE items(id bigint PRIMARY KEY,template_id text,inventory_id bigint REFERENCES pg_temp.inventories(id),stack_size integer);
      CREATE TEMP TABLE dune_exchange_orders(id bigint GENERATED BY DEFAULT AS IDENTITY(START 1000) PRIMARY KEY,
        exchange_id bigint REFERENCES pg_temp.dune_exchanges(id),access_point_id bigint REFERENCES pg_temp.dune_exchange_accesspoints(id),
        owner_id bigint REFERENCES pg_temp.actors(id),template_id text,item_id bigint REFERENCES pg_temp.items(id),item_price bigint,
        expiration_time bigint,is_npc_order boolean,durability_cur numeric,durability_max numeric,category_mask bigint,category_depth integer);
      CREATE TEMP TABLE dune_exchange_sell_orders(order_id bigint PRIMARY KEY REFERENCES pg_temp.dune_exchange_orders(id));
      CREATE TEMP TABLE dune_exchange_fulfilled_orders(order_id bigint PRIMARY KEY REFERENCES pg_temp.dune_exchange_orders(id),source_order_id bigint,completion_type integer,stack_size integer,original_order_id bigint);
      INSERT INTO pg_temp.accounts VALUES(1);
      INSERT INTO pg_temp.actors VALUES(4,1);
      INSERT INTO pg_temp.inventories VALUES(20,10);
      INSERT INTO pg_temp.dune_exchanges VALUES(10,20);
      INSERT INTO pg_temp.dune_exchange_accesspoints VALUES(11,10);
      INSERT INTO pg_temp.dune_exchange_users VALUES(1,4);
      INSERT INTO pg_temp.farm_variables VALUES((clock_timestamp() at time zone 'UTC')-interval '8220467 seconds',true);`);
    await reset();
    let expected=await inspect();
    assert.equal(expected.totalPaid,"300000");
    const results=await apply(expected);
    const receiptResult=results.find(result=>result.rows?.length);
    const receipt=purchase.parseReceipt(Object.values(receiptResult.rows[0])[0]);
    assert.equal(receipt.totalPaid,"300000");
    assert.equal(receipt.unitPrice,"100000");
    assert.equal(receipt.stackSize,"3");
    const state=(await client.query(`SELECT (SELECT count(*) FROM pg_temp.items)::int items,
      (SELECT count(*) FROM pg_temp.dune_exchange_sell_orders)::int sells,
      (SELECT expiration_time::text FROM pg_temp.dune_exchange_orders) expiry,
      (SELECT completion_type FROM pg_temp.dune_exchange_fulfilled_orders) completion`)).rows[0];
    assert.deepEqual(state,{items:0,sells:0,expiry:"999999999",completion:4});
    await assert.rejects(apply(expected),/unavailable|already purchased/);
    assert.equal((await client.query('SELECT count(*)::int n FROM pg_temp.dune_exchange_fulfilled_orders')).rows[0].n,1);
    console.log("PASS: full-stack purchase, per-unit claim value, non-expiring payout, item removal, repeat rejection.");
    for (const [change,error] of [
      ["UPDATE pg_temp.dune_exchange_orders SET item_price=200000",/changed/],
      ["UPDATE pg_temp.items SET stack_size=2",/changed/],
      ["UPDATE pg_temp.dune_exchange_orders SET expiration_time=1",/expired/],
      ["UPDATE pg_temp.dune_exchange_orders SET is_npc_order=true",/unavailable/],
      ["UPDATE pg_temp.items SET stack_size=0",/unavailable/],
      ["UPDATE pg_temp.dune_exchange_orders SET item_price=999999999",/unavailable/]
    ]) {
      await reset();expected=await inspect();await client.query(change);
      await assert.rejects(apply(expected),error);
      await assertIntact();
    }
    console.log("PASS: stale price/quantity, expired orders, NPC listings, empty stock and excessive payout rejected without partial writes.");
    await reset();expected=await inspect();
    await client.query('UPDATE pg_temp.farm_variables SET universe_time_timestamp=NULL');
    assert.equal(await inspect(),null);
    await assert.rejects(apply(expected),/unavailable/);await assertIntact();
    await client.query("UPDATE pg_temp.farm_variables SET universe_time_timestamp=(clock_timestamp() at time zone 'UTC')-interval '8220467 seconds'");
    await reset();expected=await inspect();
    await client.query(`CREATE FUNCTION pg_temp.reject_item_delete() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RETURN NULL; END';
      CREATE TRIGGER fail_item_removal BEFORE DELETE ON pg_temp.items FOR EACH ROW EXECUTE FUNCTION pg_temp.reject_item_delete();`);
    await assert.rejects(apply(expected),/Item removal verification failed/);
    await assertIntact();
    console.log("PASS: unavailable clock blocks purchase; forced last-step failure rolls back payout, fulfillment, sell row and order deletion.");
  } finally { await client.end(); }
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
