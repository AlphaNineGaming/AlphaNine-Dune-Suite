"use strict";
const assert = require("assert/strict");
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const purchase = require("../lib/market-manual-purchase");
const expected = { orderId:"18353", exchangeId:"10", accessPointId:"11", sellerActorId:"4", template:"Shotgun_Unique_LargeMag_06", itemId:"44321128", unitPrice:"100000", stackSize:"3", expirationTime:"9429712", totalPaid:"300000" };
const sql = purchase.buildApplySql(expected);
assert.match(sql, /begin;[\s\S]*for update of o,s,i;[\s\S]*commit;$/);
assert.match(sql, /p\.item_price,0,0,false/);
assert.match(sql, /values\(payment_id,null,4,p.stack_size,p.order_id\)/);
assert.match(sql, /999999999,1\.0,1\.0,p\.item_price/);
assert.match(sql, /get diagnostics affected = row_count/g);
assert.match(sql, /o\.is_npc_order=false/);
assert.match(sql, /a\.owner_account_id is not null/);
assert.match(sql, /p\.expiration_time<=p\.game_now/);
assert.match(sql, /Listing changed/);
assert.doesNotMatch(sql, /down_time_accumulation|insert into dune\.actors|solari_balance|delete from dune\.accounts/i);
for (const invalid of ["", "0", "-1", "1;drop table dune.items", "9223372036854775808"]) assert.throws(()=>purchase.buildInspectSql(invalid));
const tricky = purchase.buildApplySql({...expected,template:"O'Brien$manual_purchase$"});
assert.match(tricky, /do \$manual_purchase_\$/);
assert.match(tricky, /O''Brien\$manual_purchase\$/);
assert.throws(()=>purchase.parseReceipt(""),/could not be confirmed/);
assert.equal(purchase.parseReceipt('BEGIN\nALPHANINE_MARKET_PURCHASE:{"orderId":"18353"}\nCOMMIT').orderId,"18353");
const server = fs.readFileSync(path.join(__dirname,"..","server.js"),"utf8");
const service = server.slice(server.indexOf("const marketPurchasePreviews ="),server.indexOf("async function removeMarketListingAsAdmin("));
async function main() {
  let now=100000, sequence=0, writes=0, target={namespace:"test",dbPod:"db-0",dbSvc:"db"};
  const audit=[];
  const context={MarketManualPurchase:purchase,Date:{now:()=>now},crypto:{randomUUID:()=>String(++sequence)},gearCatalog:()=>[],cachedDatabaseRuntimeTarget:async()=>target,appendAdminAudit:(event,data)=>audit.push({event,data}),dbQuery:async query=>{
    if(query.startsWith("select json_build_object"))return JSON.stringify(expected);
    writes++;return 'ALPHANINE_MARKET_PURCHASE:'+JSON.stringify({...expected,paymentOrderId:"900"});
  }};
  vm.runInNewContext(service,context);
  await assert.rejects(context.buyMarketListingAsAdmin("18353"),/confirmation/);
  const preview=await context.previewMarketListingPurchase("18353");
  const approval={previewId:preview.previewId,confirmText:purchase.CONFIRM_TEXT};
  const results=await Promise.allSettled([context.buyMarketListingAsAdmin("18353",approval),context.buyMarketListingAsAdmin("18353",approval)]);
  assert.equal(results.filter(r=>r.status==="fulfilled").length,1);
  assert.equal(writes,1,"double-click must not send two purchase transactions");
  await assert.rejects(context.buyMarketListingAsAdmin("18353",approval),/fresh purchase preview/);
  const expired=await context.previewMarketListingPurchase("18353");now+=300001;
  await assert.rejects(context.buyMarketListingAsAdmin("18353",{previewId:expired.previewId,confirmText:purchase.CONFIRM_TEXT}),/expired/);
  const switched=await context.previewMarketListingPurchase("18353");target={...target,namespace:"other"};
  await assert.rejects(context.buyMarketListingAsAdmin("18353",{previewId:switched.previewId,confirmText:purchase.CONFIRM_TEXT}),/database changed/);
  assert.equal(writes,1);
  assert.equal(audit[0].event,"market_listing_bought_by_admin");
  const ui={esc:String,Set};
  vm.runInNewContext(server.slice(server.indexOf("const marketManualPurchasesBusy="),server.indexOf("function renderMarketListings(")),ui);
  const row={orderId:"1",playerOwned:true,isNpcOrder:false,price:100,stackSize:3,expirationTime:2000};
  assert.match(ui.marketListingPurchaseAction(row,1000),/Buy &amp; Pay/);
  for(const change of [{isNpcOrder:true},{playerOwned:false},{price:0},{expirationTime:1},{price:999999999}])assert.equal(ui.marketListingPurchaseAction({...row,...change},1000),"");
  assert.equal(ui.marketListingPurchaseAction(row,0),"");
  const wrap={innerHTML:"",querySelectorAll:()=>[]},summary={textContent:""};
  const rendering={document:{getElementById:id=>id==="marketListings"?wrap:summary},esc:value=>String(value??"").replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/"/g,"&quot;")};
  vm.runInNewContext(server.slice(server.indexOf("function formatMarketListingExpiry("),server.indexOf("async function refreshMarketListings(")),rendering);
  rendering.renderMarketListings({gameNow:1000,listings:[{...row,name:"Test item"},{...row,orderId:"2",isNpcOrder:true},{...row,orderId:"3",expirationTime:1}]});
  assert.equal((wrap.innerHTML.match(/data-market-buy=/g)||[]).length,1,"Only the eligible player row should show the purchase button");
  assert.match(wrap.innerHTML,/Buy &amp; Pay/);
  assert.match(server,/buyMarketListingAsAdmin\(buyMatch\[1\], payload\)/);
  assert.match(server,/confirmText:"BUY AND PAY"/);
  assert.match(server,/purchase: async \(\) => \{ throw new Error\("Legacy automated buying is disabled/);
  console.log("Manual player purchase: guarded SQL, per-unit payout, preview expiry, database binding, duplicate-click protection, receipt and UI eligibility checks passed.");
}
main().catch(error=>{console.error(error);process.exitCode=1;});
